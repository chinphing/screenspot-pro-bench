"""提示词与工具定义（所有基线共用）。

描述字段来自 descriptions/<split>.json：
    feat 外观特征 / ctrl 控件类型 / pos 屏幕位置 / env 周边锚点 / text 文字内容（可选）
"""
from __future__ import annotations

# ---------------------------------------------------------------- 描述
def desc_lines(d: dict, *, with_env: bool = True, with_text: bool = True) -> str:
    """把描述字段拼成提示词里的列表。

    ⚠️ 锚点(env)只给首轮，不要给校验轮——验证模型会把锚点当硬约束，产生假矛盾。
    """
    parts = []
    if with_text and d.get("text"):
        parts.append(f"· 文字内容：{d['text']}")
    parts.append(f"· 外观特征：{d['feat']}")
    parts.append(f"· 控件类型：{d['ctrl']}")
    parts.append(f"· 屏幕位置：{d['pos']}")
    if with_env and d.get("env"):
        parts.append(f"· 周边锚点：{d['env']}")
    return "\n".join(parts)


