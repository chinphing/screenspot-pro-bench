# ---------------------------------------------------------------- 工具
def tool_locate(with_ref: bool = True) -> dict:
    props = {
        "x0": {"type": "integer", "description": "目标框【左边缘】的归一化坐标（1-1000）"},
        "y0": {"type": "integer", "description": "目标框【上边缘】的归一化坐标（1-1000）"},
        "x1": {"type": "integer", "description": "目标框【右边缘】的归一化坐标（1-1000）"},
        "y1": {"type": "integer", "description": "目标框【下边缘】的归一化坐标（1-1000）"},
        "reason": {"type": "string", "description": "你看到的情况（一句话）"},
    }
    req = ["x0", "y0", "x1", "y1"]
    if with_ref:
        props["ref"] = {"type": "string", "enum": ["原图", "放大图"],
                        "description": "你在哪张图上框的：「放大图」= 局部放大那张（更清楚，推荐）；「原图」= 完整界面那张。"}
        req = ["ref"] + req
    return {"type": "function", "function": {
        "name": "locate",
        "description": "在图上框出目标元素的位置，报出目标的外接矩形（框住整个元素）。"
                       "如果这一轮在图上找不到目标，就不要调用这个工具。",
        "parameters": {"type": "object", "properties": props, "required": req}}}


